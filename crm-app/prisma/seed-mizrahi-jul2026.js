// פונקציה ראשית
// ============================================================
async function main() {
  console.log('🏦 עדכון משרות בנק מזרחי – יולי 2026\n' + '='.repeat(55));

  const employer = await prisma.employer.findFirst({
    where: { name: { contains: 'מזרחי' } }
  });

  if (!employer) {
    console.error('❌ לא נמצא מעסיק בנק מזרחי!');
    process.exit(1);
  }
  console.log(`✅ מעסיק: ${employer.name} (ID: ${employer.id})`);

  // מחיקת כל המשרות הקיימות של מזרחי
  const before = await prisma.position.count({ where: { employerId: employer.id } });
  console.log(`📊 משרות קיימות: ${before}`);
  const del = await prisma.position.deleteMany({ where: { employerId: employer.id } });
  console.log(`🗑️  נמחקו ${del.count} משרות ישנות\n`);

  console.log(`📝 יוצר ${positions.length} משרות חדשות...\n`);
  let created = 0, errors = 0;

  for (const pos of positions) {
    try {
      const desc = buildDesc({
        title: pos.title,
        area: pos.area,
        code: pos.code,
        branchType: pos.branchType,
        posType: pos.posType,
        salary: pos.salary,
        location: pos.location,
        extra: pos.extra
      });

      const position = await prisma.position.create({
        data: {
          title:          pos.title,
          location:       pos.location,
          description:    desc,
          requirements:   pos.requirements,
          salaryRange:    pos.salary.split('\n')[0].replace('💰 ', '').trim(),
          employmentType: 'משרה מלאה',
          active:         true,
          employerId:     employer.id,
          keywords:       JSON.stringify(pos.keywords),
          openings:       1,
          contactName:    'סמדר',
          contactEmail:   EMAIL_SMADAR,
          contactEmails:  JSON.stringify([
            { email: EMAIL_SMADAR,  name: 'סמדר' },
            { email: EMAIL_SYSTEM,  name: 'מערכת גיוס מזרחי' }
          ]),
          workHours:  pos.branchType.includes('מפוצל') ? 'ב\'-ו\' כולל פיצולים' : 'א\'-ה\' + שישי',
          benefits:   'קרן השתלמות (בנקאים מהיום הראשון) | מענק התמדה (טלרים) | נסיעות | שעות נוספות',
          priority:   pos.title.includes('דחוף') ? 5 : (pos.title.includes('מתנייד') ? 3 : 2)
        }
      });

      for (const tagName of pos.tags) {
        const tag = await getOrCreateTag(tagName);
        await prisma.position.update({ where: { id: position.id }, data: { tags: { connect: { id: tag.id } } } });
      }

      console.log(`✅ ${pos.title}`);
      created++;
    } catch (e) {
      console.error(`❌ שגיאה: ${pos.title}: ${e.message}`);
      errors++;
    }
  }

  console.log(`\n${'='.repeat(55)}`);
  console.log(`🎉 הושלם! נוצרו: ${created} | שגיאות: ${errors}`);

  // סיכום לפי מרחב
  const byArea = {};
  for (const p of positions) {
    byArea[p.area] = (byArea[p.area] || 0) + 1;
  }
  console.log('\n📊 לפי מרחב:');
  for (const [a, c] of Object.entries(byArea)) console.log(`   ${a}: ${c} משרות`);

  // בדיקת keywords
  const allPos = await prisma.position.findMany({
    where: { employerId: employer.id },
    select: { title: true, keywords: true }
  });
  const lowKw = allPos.filter(p => !p.keywords || JSON.parse(p.keywords).length < 40);
  if (lowKw.length === 0) console.log('\n✅ כל המשרות עם 40+ מילות מפתח!');
  else lowKw.forEach(p => console.log(`⚠️  פחות מ-40 kw: ${p.title}`));
}

main()
  .catch(e => { console.error('💥 שגיאה קריטית:', e.message); process.exit(1); })
  .finally(() => prisma.$disconnect());
