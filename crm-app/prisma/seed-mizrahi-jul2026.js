  let d = `${title}\n`;
  d += `🏦 בנק מזרחי טפחות | קוד משרה: ${code}\n`;
  d += `📍 מיקום: ${location}\n`;
  if (area) d += `🗺️ מרחב: ${area}\n`;
  d += `\n`;
  if (branchType) d += `📋 סוג סניף: ${branchType}\n`;
  if (posType) d += `📌 סוג תקן: ${posType}\n`;
  d += `\n${salary}\n`;
  if (extra) d += `\nℹ️ ${extra}\n`;
  return d.trim();
