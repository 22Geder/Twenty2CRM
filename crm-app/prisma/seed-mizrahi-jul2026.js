// ---- פונקציות עזר ----
async function getOrCreateTag(name) {
  let tag = await prisma.tag.findFirst({ where: { name } });
  if (!tag) {
    tag = await prisma.tag.create({ data: { name, type: 'POSITION', color: '#1e40af' } });
  }
  return tag;
}

