const POSITIONS = [COLLECTIONS, LEGAL_COLLECTIONS, ...TECHNICIANS, RAMP_DRIVER, ...DISTRIBUTION, ...RESERVE, LAB_TECH, WAREHOUSE];

module.exports = { EMPLOYER, POSITIONS };

async function main() {
  const { PrismaClient } = require('@prisma/client');
  const prisma = new PrismaClient();
  const APPLY = process.argv.includes('--apply');
  try {
    console.log(`מצב: ${APPLY ? 'APPLY' : 'DRY-RUN'} | ${POSITIONS.length} משרות`);
    let employer = await prisma.employer.findFirst({
      where: { OR: [{ name: EMPLOYER.name }, { email: EMPLOYER.email }] },
    });
    console.log(employer ? `מעסיק קיים: ${employer.id} (${employer.name})` : `+ מעסיק חדש: ${EMPLOYER.name}`);
    if (APPLY && !employer) employer = await prisma.employer.create({ data: EMPLOYER });

    for (const p of POSITIONS) {
      const existing = employer
        ? await prisma.position.findFirst({
            where: { employerId: employer.id, title: { equals: p.title, mode: 'insensitive' }, location: { equals: p.location, mode: 'insensitive' } },
            select: { id: true },
          })
        : null;
      if (!APPLY) { console.log(`${existing ? '~ עדכון' : '+ חדשה'}: ${p.title} | ${p.location.split(',')[0]}`); continue; }

      const tagRows = [];
      for (const name of p.tags) {
        const found = await prisma.tag.findFirst({ where: { name: { equals: name, mode: 'insensitive' } } });
        tagRows.push(found || await prisma.tag.create({ data: { name, type: 'SKILL', color: '#16A34A' } }));
      }
      const data = {
        title: p.title,
        description: p.description,
        requirements: p.requirements,
        location: p.location,
        employmentType: p.employmentType,
        workHours: p.workHours,
        salaryRange: p.salaryRange,
        benefits: p.benefits,
        transportation: p.transportation ?? null,
        keywords: JSON.stringify([...new Set(p.tags)]),
        active: true,
      };
      if (existing) {
        await prisma.position.update({ where: { id: existing.id }, data: { ...data, tags: { set: tagRows.map((t) => ({ id: t.id })) } } });
        console.log(`עודכנה: ${p.title} | ${existing.id}`);
      } else {
        const created = await prisma.position.create({
          data: { ...data, employerId: employer.id, tags: { connect: tagRows.map((t) => ({ id: t.id })) } },
          select: { id: true },
        });
        console.log(`נוצרה: ${p.title} | ${created.id}`);
      }
    }
    if (!APPLY) console.log('Dry-run בלבד. להוספה בפועל: --apply');
  } finally {
    await prisma.$disconnect();
  }
}

if (require.main === module) {
  main().catch((e) => { console.error('שגיאה:', e.message); process.exitCode = 1; });
}
