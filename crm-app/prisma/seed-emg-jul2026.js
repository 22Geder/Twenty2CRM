async function main() {
  console.log('🏢 עדכון משרות קבוצת EMG / MRG - יולי 2026\n' + '='.repeat(55));

  // מציאת המעסיק
  const employer = await prisma.employer.findFirst({
    where: { OR: [{ name: { contains: 'MRG' } }, { name: { contains: 'EMG' } }, { email: 'hr@mrg-group.co.il' }] }
  });

  if (!employer) {
    console.error('❌ לא נמצא מעסיק קבוצת MRG/EMG! בטל הרצה.');
    process.exit(1);
  }
  console.log(`✅ מעסיק נמצא: ${employer.name} (ID: ${employer.id})`);

  // מחיקת משרות קיימות
  const before = await prisma.position.count({ where: { employerId: employer.id } });
  console.log(`📊 משרות קיימות לפני עדכון: ${before}`);
  const del = await prisma.position.deleteMany({ where: { employerId: employer.id } });
  console.log(`🗑️  נמחקו ${del.count} משרות ישנות\n`);

  console.log(`📝 יוצר ${positions.length} משרות חדשות...\n`);
  let created = 0, errors = 0;

  for (const pos of positions) {
    try {
      const description = buildDesc({
        role: pos.role, brand: pos.brand, location: pos.location,
        openings: pos.openings, salary: pos.salary, date: pos.date,
        shabbat: pos.shabbat, extra: pos.extra, fullDesc: pos.fullDesc
      });

      const position = await prisma.position.create({
        data: {
          title:          pos.title,
          location:       pos.location,
          description,
          requirements:   pos.requirements,
          salaryRange:    pos.salary,
          employmentType: 'משרה מלאה',
          active:         true,
          employerId:     employer.id,
          keywords:       JSON.stringify(pos.keywords),
          openings:       pos.openings || 1,
          contactName:    pos.recruiter,
          contactEmail:   pos.email,
          benefits:       pos.benefits || null,
          workHours:      pos.workHours || null,
          priority:       pos.priority || 1
        }
      });

      for (const tagName of pos.tags) {
        const tag = await getOrCreateTag(tagName);
        await prisma.position.update({ where: { id: position.id }, data: { tags: { connect: { id: tag.id } } } });
      }

      console.log(`✅ ${position.title}`);
      created++;
    } catch (e) {
      console.error(`❌ שגיאה: ${pos.title}: ${e.message}`);
      errors++;
    }
  }

  console.log(`\n${'='.repeat(55)}`);
  console.log(`🎉 הושלם! נוצרו: ${created} | שגיאות: ${errors}`);

  // סיכומים
  const byBrand = {}, byRecruiter = {};
  for (const p of positions) {
    byBrand[p.brand] = (byBrand[p.brand] || 0) + 1;
    byRecruiter[p.recruiter] = (byRecruiter[p.recruiter] || 0) + 1;
  }
  console.log('\n📊 לפי מותג/חברה:');
  for (const [b, c] of Object.entries(byBrand)) console.log(`   ${b}: ${c}`);
  console.log('\n📊 לפי מגייס:');
  for (const [r, c] of Object.entries(byRecruiter)) console.log(`   ${r}: ${c}`);
}

main()
  .catch((e) => { console.error('💥 שגיאה קריטית:', e); process.exit(1); })
  .finally(async () => { await prisma.$disconnect(); });
