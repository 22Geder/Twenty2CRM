async function main() {
  console.log('🔧 מתקן keywords + בודק מיקומים...\n');

  let fixed = 0;

  for (const fix of fixes) {
    // ודא exactly 40 מילות מפתח
    const unique = [...new Set(fix.keywords)];
    if (unique.length !== 40) {
      console.warn(`⚠️  ${fix.title}: ${unique.length} מילות מפתח (צפוי 40)`);
    }

    const result = await prisma.position.updateMany({
      where: { title: fix.title },
      data: { keywords: JSON.stringify(unique) }
    });

    if (result.count > 0) {
      console.log(`✅ עודכן (${unique.length} kw): ${fix.title}`);
      fixed++;
    } else {
      console.warn(`❌ לא נמצא: ${fix.title}`);
    }
  }

  // בדיקת כל המשרות - ודא ≥40 keywords
  console.log('\n📊 בדיקה סופית של כל המשרות:');
  const positions = await prisma.position.findMany({
    where: { employerId: 'bc525083-0c35-402f-9f47-f3d5365841b8' },
    select: { title: true, location: true, keywords: true, tags: { select: { name: true } } },
    orderBy: { title: 'asc' }
  });

  let ok = 0, low = 0;
  for (const pos of positions) {
    const kwCount = pos.keywords ? JSON.parse(pos.keywords).length : 0;
    const tagCount = pos.tags.length;
    const status = kwCount >= 40 ? '✅' : '❌';
    if (kwCount >= 40) ok++;
    else {
      low++;
      console.log(`${status} kw=${kwCount} tags=${tagCount} | ${pos.title}`);
    }
  }

  console.log(`\n✅ תקין (≥40 kw): ${ok}/${positions.length}`);
  if (low > 0) console.log(`❌ עם פחות מ-40: ${low}`);
  else console.log('🎉 כל המשרות עם 40+ מילות מפתח!');

  // בדיקת מיקומים
  console.log('\n📍 בדיקת מיקומים:');
  const locationCheck = await prisma.position.findMany({
    where: {
      employerId: 'bc525083-0c35-402f-9f47-f3d5365841b8',
      OR: [
        { location: { contains: 'מטה' } },
        { location: { equals: '' } },
        { location: null }
      ]
    },
    select: { title: true, location: true }
  });

  if (locationCheck.length === 0) {
    console.log('✅ כל המיקומים תקינים (אין "מטה" ואין ריקים)');
  } else {
    locationCheck.forEach(p => console.log(`⚠️  ${p.title} | מיקום: "${p.location}"`));
  }

  console.log(`\n📋 סיכום כל המשרות (${positions.length} סה"כ):`);
  positions.forEach(p => {
    const kw = p.keywords ? JSON.parse(p.keywords).length : 0;
    console.log(`  ${kw >= 40 ? '✅' : '❌'} kw=${kw} | ${p.title} | ${p.location}`);
  });
}

main()
  .catch(e => { console.error('💥', e.message); process.exit(1); })
  .finally(() => prisma.$disconnect());
