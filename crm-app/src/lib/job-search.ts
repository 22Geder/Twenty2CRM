type Group = { normSet: Set<string> }
const NORM_GROUPS: Group[] = SYNONYM_GROUPS.map((words) => ({
  normSet: new Set(words.map(normalizeHe).filter(Boolean)),
}))

/**
 * מרחיב מילה בודדת (מנורמלת) לרשימת מונחים:
 * המילה עצמה + כל המילים הנרדפות מקטגוריות שהיא נוגעת בהן.
 */
function expandWord(word: string): string[] {
  const terms = new Set<string>([word])
  for (const group of NORM_GROUPS) {
    let hit = false
    for (const w of group.normSet) {
      // התאמה דו-כיוונית: "מחסנ"⊂"מחסנאי" וגם "מחסנאי"⊃"מחסנ"
      if (w.includes(word) || word.includes(w)) {
        hit = true
        break
      }
    }
    if (hit) for (const w of group.normSet) terms.add(w)
  }
  return [...terms]
}

/**
 * מרחיב שאילתה שלמה לרשימת מונחים (לשם תצוגה/דיבוג).
 * מאחד את ההרחבות של כל המילים.
 */
export function expandSearchTerms(query: string): string[] {
  const q = normalizeHe(query)
  if (!q) return []
  const all = new Set<string>()
  for (const word of q.split(" ")) {
    if (!word) continue
    for (const t of expandWord(word)) all.add(t)
  }
  return [...all]
}

/**
 * בונה פונקציית התאמה מדויקת עבור שאילתה.
 *
 * דיוק: כל מילה בשאילתה חייבת להימצא (AND בין מילים), כאשר כל מילה
 * מורחבת למילים נרדפות (OR בתוך קבוצת המילה). כך:
 *   "מחסן אשדוד" → משרות מחסן (מחסנאי/מלגזן/מלקט...) *וגם* באשדוד.
 *   "טלר ירושלים" → טלר/בנקאי *וגם* בירושלים.
 * מילה בת תו אחד מתעלמים ממנה (רעש).
 *
 * מחזיר null אם אין שאילתה משמעותית — כלומר אין לסנן לפי טקסט.
 */
export function buildSearchMatcher(query: string): ((normText: string) => boolean) | null {
  const q = normalizeHe(query)
  if (!q) return null

  const wordGroups = q
    .split(" ")
    .filter((w) => w.length >= 1)
    .map((w) => expandWord(w))

  if (wordGroups.length === 0) return null

  return (normText: string) =>
    wordGroups.every((terms) => terms.some((t) => normText.includes(t)))
}

/**
 * בונה פונקציית התאמה סמנטית לרשימת מילות־מפתח של קטגוריה.
 *
 * בשונה מ-buildSearchMatcher (שדורש שכל המילים יופיעו - AND), כאן נדרש
 * שלפחות `minMatches` *מילות־בסיס שונות* מהרשימה יופיעו בטקסט (כל מילה
 * מורחבת לנרדפות שלה, אך נספרת פעם אחת). כך משיגים דיוק: משרת תוכנה אמיתית
 * מזכירה בדרך כלל 2+ מונחים ("מפתח" + "תוכנה"), בעוד אזכור מקרי יחיד נחסם.
 *
 * דוגמה: "תוכנה מתכנת developer פיתוח" עם minMatches=2 → המשרה חייבת להכיל
 * לפחות שתיים מהמילים הללו (או נרדפות שלהן) כדי להיחשב התאמה.
 *
 * מחזיר null אם אין שאילתה משמעותית.
 */
export function buildSemanticMatcher(
  query: string,
  minMatches = 2,
): ((normText: string) => boolean) | null {
  const q = normalizeHe(query)
  if (!q) return null

  // כל מילת־בסיס → ההרחבה הנרדפת שלה. מילים נרדפות מאותה קטגוריה מקבלות
  // הרחבה זהה, ולכן נאחד אותן ל"מושג" אחד כדי שהסף יספור מושגים שונים
  // (ולא ניפוח של נרדפות): "בנק/טלר/בנקאי" = מושג אחד, "תוכנה" ו"פיתוח" = שניים.
  const byConcept = new Map<string, string[]>()
  for (const word of q.split(" ").filter(Boolean)) {
    const terms = expandWord(word)
    const key = [...terms].sort().join("|")
    if (!byConcept.has(key)) byConcept.set(key, terms)
  }
  const concepts = [...byConcept.values()]
  if (concepts.length === 0) return null

  // הסף הוא מספר המושגים השונים שנדרשים; לא יעלה על מספר המושגים הזמינים
  // (תגית עם מושג אחד בלבד תדרוש התאמה אחת, כדי לא לחסום אותה לחלוטין).
  const need = Math.min(minMatches, concepts.length)

  return (normText: string) => {
    let hits = 0
    for (const terms of concepts) {
      if (terms.some((t) => normText.includes(t))) {
        hits++
        if (hits >= need) return true
      }
    }
    return false
  }
}
