async function getOrCreateTag(name) {
  let tag = await prisma.tag.findFirst({ where: { name } });
  if (!tag) {
    tag = await prisma.tag.create({ data: { name, type: 'POSITION', color: '#8b5cf6' } });
  }
  return tag;
}

function buildDesc({ role, brand, location, openings, salary, date, shabbat, extra, fullDesc }) {
  if (fullDesc) return fullDesc.trim();
  let d = `דרוש/ה ${role} לסניף ${brand} ${location}!\n\n`;
  d += `📍 מיקום: ${location}\n`;
  d += `🏢 חברה: ${brand} (קבוצת EMG)\n`;
  if (openings && openings > 1) d += `👥 מספר משרות: ${openings}\n`;
  d += `\n💰 שכר: ${salary}\n`;
  if (date) d += `📅 תאריך פתיחה: ${date}\n`;
  if (shabbat === 'כולל') d += `📆 כולל עבודה בשבת\n`;
  else if (shabbat === 'לא כולל') d += `📆 ללא עבודה בשבת\n`;
  if (extra) d += `\n${extra}\n`;
  return d.trim();
}

