async function main() {
  console.log('🔧 מתקן 4 משרות מתנייד – keywords → 40\n');
  let fixed = 0;
  for (const fix of fixes) {
    const unique = [...new Set(fix.keywords)];
    console.log(`  ${fix.title.substring(0, 50)}... → ${unique.length} kw`);
    const r = await prisma.position.updateMany({
      where: { title: fix.title },
      data: { keywords: JSON.stringify(unique) }
    });
    if (r.count > 0) { console.log(`  ✅ עודכן`); fixed++; }
    else console.log(`  ❌ לא נמצא!`);
  }

  // בדיקה סופית
  const all = await prisma.position.findMany({
    where: { employer: { name: { contains: 'מזרחי' } } },
    select: { title: true, location: true, keywords: true, tags: { select: { name: true } } },
    orderBy: { title: 'asc' }
  });
  console.log(`\n📊 בדיקה סופית – ${all.length} משרות:`);
  let ok = 0, low = 0;
  for (const pos of all) {
    const kw = pos.keywords ? JSON.parse(pos.keywords).length : 0;
    const tags = pos.tags.length;
    const status = kw >= 40 ? '✅' : '❌';
    if (kw >= 40) ok++;
    else { low++; console.log(`  ${status} kw=${kw} tags=${tags} | ${pos.title}`); }
  }
  console.log(`\n✅ תקין: ${ok}/${all.length}`);
  if (low === 0) console.log('🎉 כל המשרות עם 40+ מילות מפתח!');

  console.log('\n📋 רשימה מלאה:');
  all.forEach(p => {
    const kw = p.keywords ? JSON.parse(p.keywords).length : 0;
    console.log(`  ${kw >= 40 ? '✅' : '❌'} kw=${kw} | ${p.title} | ${p.location}`);
  });
}

main()
  .catch(e => { console.error('💥', e.message); process.exit(1); })
  .finally(() => prisma.$disconnect());
