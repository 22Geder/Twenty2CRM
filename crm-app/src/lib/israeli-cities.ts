// נרמול מחרוזת לצורך התאמה: הסרת גרשיים, המרת מפרידים לרווח, איחוד רווחים.
function normalizeForMatch(input: string): string {
  return input
    .replace(/[׳״'"`’‘]/g, "")
    .replace(/[\-\/|,.()\[\]]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase()
}

type CityEntry = { canonical: string; normAlias: string }

// בניית רשימת כל (שם קנוני, כינוי מנורמל) — כולל השם הקנוני עצמו — ממוינת
// לפי אורך יורד, כדי ששמות ארוכים ("גן יבנה") ייבדקו לפני קצרים ("יבנה").
const CITY_ENTRIES: CityEntry[] = Object.entries(CITY_ALIASES)
  .flatMap(([canonical, aliases]) =>
    [canonical, ...aliases].map((alias) => ({
      canonical,
      normAlias: normalizeForMatch(alias),
    }))
  )
  .filter((e) => e.normAlias.length > 0)
  .sort((a, b) => b.normAlias.length - a.normAlias.length)

/**
 * מזהה את כל הערים המופיעות בטקסט מיקום חופשי.
 * מחזיר שמות קנוניים ייחודיים. משרה רב-עירונית תחזיר כמה ערים.
 */
export function extractCities(location?: string | null): string[] {
  if (!location) return []

  let working = normalizeForMatch(location)
  if (!working) return []

  const found = new Set<string>()

  for (const { canonical, normAlias } of CITY_ENTRIES) {
    if (found.has(canonical)) continue
    if (working.includes(normAlias)) {
      found.add(canonical)
      // "צריכה" של ההתאמה כדי ששמות קצרים המוכלים בה לא ייתפסו בטעות
      // (למשל "גן יבנה" לא ייחשב גם כ"יבנה").
      working = working.split(normAlias).join(" ")
    }
  }

  return [...found]
}

/**
 * ממיין רשימת ערים לפי א"ב עברי.
 */
export function sortCitiesHe(cities: string[]): string[] {
  return [...cities].sort((a, b) => a.localeCompare(b, "he"))
}
