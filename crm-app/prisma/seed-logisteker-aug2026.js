async function main() {
  console.log('🏭 עדכון משרות לוגיסטיקר – אוגוסט 2026');
  console.log('=======================================================');

  const employer = await prisma.employer.findUnique({ where: { id: EMPLOYER_ID } });
  if (!employer) { console.error('❌ מעסיק לא נמצא!'); process.exit(1); }
  console.log(`✅ מעסיק: ${employer.name} (${EMPLOYER_ID})`);

  // מחיקת כל המשרות הקיימות
  const existing = await prisma.position.findMany({ where: { employerId: EMPLOYER_ID }, select: { id: true } });
  console.log(`📊 משרות קיימות: ${existing.length}`);

  // מחיקת applications, interviews, tags
  for (const pos of existing) {
    await prisma.application.deleteMany({ where: { positionId: pos.id } });
    await prisma.interview.deleteMany({ where: { positionId: pos.id } });
    await prisma.position.update({ where: { id: pos.id }, data: { tags: { set: [] } } });
  }
  await prisma.position.deleteMany({ where: { employerId: EMPLOYER_ID } });
  console.log(`🗑️  נמחקו ${existing.length} משרות ישנות\n`);

  const tag = await getOrCreateTag('לוגיסטיקר');

  console.log(`📝 יוצר ${POSITIONS.length} משרות חדשות (מושהות – active=false)...\n`);
  let created = 0, errors = 0;

  for (const pos of POSITIONS) {
    try {
      const kw = pos.keywords ? JSON.parse(pos.keywords) : [];
      const newPos = await prisma.position.create({
        data: {
          title: pos.title,
          description: pos.description || null,
          requirements: pos.requirements || null,
          location: pos.location || null,
          salaryRange: pos.salaryRange || null,
          workHours: pos.workHours || null,
          benefits: pos.benefits || null,
          transportation: pos.transportation || null,
          employmentType: 'Full-time',
          keywords: JSON.stringify(kw),
          active: false,   // ⏸ מושהה – AI לא יציע
          priority: 0,
          openings: 1,
          employerId: EMPLOYER_ID,
          tags: { connect: [{ id: tag.id }] }
        }
      });
      console.log(`⏸ ${pos.title}`);
      console.log(`   📍 ${pos.location} | 💰 ${pos.salaryRange || '—'} | kw=${kw.length}`);
      created++;
    } catch (e) {
      console.error(`❌ שגיאה ב-${pos.title}:`, e.message);
      errors++;
    }
  }

  console.log('\n=======================================================');
  console.log(`✅ נוצרו: ${created} | ❌ שגיאות: ${errors}`);
  console.log('⏸  כל המשרות מושהות (active=false) – AI לא יציע אותן');

  // בדיקת keywords
  const all = await prisma.position.findMany({
    where: { employerId: EMPLOYER_ID },
    select: { title: true, keywords: true, active: true }
  });
  const low = all.filter(p => !p.keywords || JSON.parse(p.keywords).length < 40);
  if (low.length > 0) {
    console.log('\n⚠️  פחות מ-40 kw:');
    low.forEach(p => console.log(`   ${JSON.parse(p.keywords || '[]').length} kw | ${p.title}`));
  } else {
    console.log('🎉 כל המשרות עם 40 מילות מפתח!');
  }
}

main()
  .catch(e => { console.error('💥', e.message); process.exit(1); })
  .finally(() => prisma.$disconnect());
