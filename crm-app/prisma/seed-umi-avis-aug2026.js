// ========= MAIN =========
async function main() {
  console.log('🏪 עדכון משרות קבוצת UMI AVIS – אוגוסט 2026');
  console.log('='.repeat(60));

  const employer = await prisma.employer.findUnique({ where: { id: EMPLOYER_ID } });
  if (!employer) throw new Error('מעסיק לא נמצא! ID: ' + EMPLOYER_ID);
  console.log(`✅ מעסיק: ${employer.name}`);

  const existing = await prisma.position.count({ where: { employerId: EMPLOYER_ID } });
  console.log(`📊 קיימות: ${existing}`);
  if (existing > 0) {
    await prisma.position.deleteMany({ where: { employerId: EMPLOYER_ID } });
    console.log(`🗑️  נמחקו ${existing} ישנות`);
  }

  const tagUMI = await ensureTag('UMI AVIS');
  const tagLis = await ensureTag('ליסינג');
  const tagOff = await ensureTag('Office Depot');

  console.log(`\n📝 יוצר ${POSITIONS.length} משרות...`);
  let created = 0, errors = 0;

  for (const pos of POSITIONS) {
    try {
      const kwArr = JSON.parse(pos.kw);
      const tagsConnect = [{ id: tagUMI.id }];
      if (pos.t.includes('אופיס') || pos.t.includes('Office') || pos.t.includes('מלקט') || pos.t.includes('סג') && pos.t.includes('מנהל') || pos.t.includes('מנהל/ת סניף')) tagsConnect.push({ id: tagOff.id });
      if (pos.t.includes('ליסינג') || pos.t.includes('קאר קונטרול') || pos.t.includes('בית לקוח')) tagsConnect.push({ id: tagLis.id });

      await prisma.position.create({
        data: {
          title:          pos.t,
          description:    pos.desc || null,
          requirements:   pos.req || null,
          location:       pos.loc,
          salaryRange:    pos.sal || null,
          workHours:      pos.h || null,
          benefits:       pos.ben || null,
          transportation: pos.transport || null,
          contactEmail:   'hr@umi-avis.co.il',
          employmentType: 'Full-time',
          keywords:       pos.kw,
          active:         true,
          priority:       0,
          openings:       pos.o || 1,
          employerId:     EMPLOYER_ID,
          tags:           { connect: tagsConnect }
        }
      });
      console.log(`✅ kw=${kwArr.length} | ${pos.t}`);
      created++;
    } catch (e) {
      console.error(`❌ ${pos.t}: ${e.message}`);
      errors++;
    }
  }

  console.log('\n' + '='.repeat(60));
  console.log(`✅ נוצרו: ${created} | ❌ שגיאות: ${errors}`);

  const all = await prisma.position.findMany({ where: { employerId: EMPLOYER_ID }, select: { keywords: true, title: true } });
  const low = all.filter(p => !p.keywords || JSON.parse(p.keywords).length < 50);
  if (low.length === 0) console.log(`🎉 כל ${all.length} משרות עם 50+ מילות מפתח!`);
  else {
    console.log(`⚠️  ${low.length} עם פחות מ-50:`);
    low.forEach(p => console.log(`   - ${p.title}: ${p.keywords ? JSON.parse(p.keywords).length : 0} kw`));
  }
}

main().catch(e => { console.error('💥', e.message); process.exit(1); }).finally(() => prisma.$disconnect());
