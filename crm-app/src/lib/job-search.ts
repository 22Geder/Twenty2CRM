// קיפול אותיות סופיות + הסרת ניקוד, גרשיים, וריווח מיותר.
export function normalizeHe(input?: string | null): string {
  if (!input) return ""
  return input
    .replace(/[\u0591-\u05C7]/g, "") // ניקוד וטעמים
    .replace(/[׳״'"`’‘]/g, "")
    .replace(/ך/g, "כ")
    .replace(/ם/g, "מ")
    .replace(/ן/g, "נ")
    .replace(/ף/g, "פ")
    .replace(/ץ/g, "צ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase()
}

